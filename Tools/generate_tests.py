"""
Generate pytest test files from the Katalon test-case scripts and suites.

    python Tools/generate_tests.py --katalon ../Commons_Automation --apps C3DC GC

For every Katalon test case  Test Cases/<APP>_TestCases/<...>/<TC name>  it writes
    Testcases/<app>/<...>/test_<TC_name>.py

  * The steps are translated one-to-one into calls on the app object (see Commons/apps/base.py).
  * Markers come from the Katalon suites: a test that is in C3DC_Smoke gets @pytest.mark.smoke, one
    in C3DC_Regression / _part1 / _part2 ... gets @pytest.mark.regression, QuickRun -> quickrun.
  * A script with steps this generator does not understand is still written, but marked skip and
    listed at the end, so nothing silently passes.
  * Static-page tests and the standalone Python "QuickRun" scripts are not generated (they are
    hand-written / out of scope); they are listed as well.

Safe to re-run: it overwrites files with the `# GENERATED` header only.
"""
import argparse
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from Commons.object_repository import ObjectRepository  # noqa: E402

HEADER = "# GENERATED by Tools/generate_tests.py from the Katalon test case. Edit freely; re-running skips edited files.\n"

# Katalon Test Suite file stem -> pytest marker.
# GC suites: keys are still CDS_*.ts in Commons_Automation (legacy Katalon names).
SUITE_MARKERS = {
    "C3DC_Smoke": "smoke",
    "C3DC_Regression": "regression",
    "C3DC_Regression_Upd": "regression",
    "C3DC_part1": "regression",
    "C3DC_part2": "regression",
    "C3DC_QuickRun": "quickrun",
    "CDS_Smoke": "smoke",                    # GC smoke
    "CDS_Regression_Full": "regression",   # GC regression
    "CDS_Subset-1": "regression",
    "CDS_Subset-2": "regression",
    "CDS_QuickRun": "quickrun",              # GC quickrun
}
FIXTURE = {"C3DC": "c3dc", "GC": "gc"}
# All Explore Participants result tabs (after read_statbar) — matches hand-maintained C3DC tests.
C3DC_VERIFY_TABS = (
    "Participants",
    "Studies",
    "Diagnosis",
    "Genetic Analysis",
    "Treatments",
    "Treatment Responses",
    "Survival",
    "Samples",
)
# Framework app GC is stored under CDS_* paths in the Katalon project.
KATALON_APP = {"GC": "CDS"}

# tests that are hand-written instead of generated (static pages etc.)
HAND_WRITTEN_MARKERS = ("verifyStaticData",)
OUT_OF_SCOPE_MARKERS = ("PythonReader",)


# --------------------------------------------------------------------------- parsing Groovy
def strip_comments(src: str) -> str:
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    lines = []
    for line in src.splitlines():
        s = line.strip()
        if s.startswith("//") or s.startswith("import "):
            continue
        lines.append(line)
    return "\n".join(lines)


CALL_RE = re.compile(r"CustomKeywords\.'utilities\.(\w+)\.(\w+)'\s*\(|WebUI\.(\w+)\s*\(")


def _match_paren(text: str, start: int) -> int:
    """Index of the ')' matching the '(' just before `start`, ignoring quoted text."""
    depth, i, quote = 1, start, None
    while i < len(text):
        ch = text[i]
        if quote:
            if ch == "\\":
                i += 1
            elif ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    return len(text)


def _split_args(arg_text: str):
    args, depth, quote, cur = [], 0, None, ""
    for ch in arg_text:
        if quote:
            cur += ch
            if ch == quote:
                quote = None
            continue
        if ch in "'\"":
            quote = ch
            cur += ch
        elif ch in "([":
            depth += 1
            cur += ch
        elif ch in ")]":
            depth -= 1
            cur += ch
        elif ch == "," and depth == 0:
            args.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur.strip())
    return args


def _unquote(a: str) -> str:
    a = a.strip()
    m = re.fullmatch(r"findTestObject\(\s*(['\"])(.*?)\1\s*\)", a, flags=re.S)
    if m:
        a = m.group(2)
        return a
    if len(a) >= 2 and a[0] in "'\"" and a[-1] == a[0]:
        return a[1:-1]
    return a


def parse_calls(src: str):
    """[(kind, name, [args])] in source order. kind is 'kw' (custom keyword) or 'webui'."""
    calls = []
    for m in CALL_RE.finditer(src):
        end = _match_paren(src, m.end())
        args = _split_args(src[m.end():end])
        if m.group(2):
            calls.append(("kw", m.group(2), args, m.group(1)))
        else:
            calls.append(("webui", m.group(3), args, "WebUI"))
    return calls


# --------------------------------------------------------------------------- translating steps
def _obj_parts(path: str, app: str):
    p = _unquote(path).replace("Object Repository/", "")
    if p.startswith(app + "/"):
        p = p[len(app) + 1:]
    return p.split("/")


class Translator:
    def __init__(self, app: str, repo: ObjectRepository):
        self.app, self.repo = app, repo
        self.v = FIXTURE[app]
        self.steps, self.todo, self.banner_done = [], [], False

    def emit(self, line): self.steps.append(f"    {line}")

    def unconverted(self, what):
        self.todo.append(what)
        self.steps.append(f"    # TODO not converted: {what}")

    def translate(self, calls):
        v = self.v
        c3dc_read_statbar = False
        for kind, name, args, owner in calls:
            if kind == "webui":
                if name in ("closeBrowser", "openBrowser", "delay", "waitForElementPresent",
                            "waitForElementVisible", "setViewPortSize", "maximizeWindow"):
                    continue
                self.unconverted(f"WebUI.{name}({', '.join(args)})")
                continue
            if name == "RunKatalon":
                self.emit(f'{v}.load_query_file("{_unquote(args[0])}")')
            elif name in ("clickTab", "clickTabCDSStat"):
                self.click(_unquote(args[0]))
            elif name.startswith("readStatBar"):
                self.emit(f"{v}.read_statbar()")
                if self.app == "C3DC":
                    c3dc_read_statbar = True
            elif name == "multiFunction":
                if self.app == "C3DC" and c3dc_read_statbar:
                    continue
                self.emit(f'{v}.verify_tab("{self.tab_name(args)}")')
            elif name in ("openTab", "selectTab", "selectTabByDropdown", "scrollFacetDownUntilVisible", "ScrollToStudyName"):
                continue           # C3DC: verify_tab uses selectTab-style open_tab; select_filter scrolls checkboxes
            else:
                self.unconverted(f"{owner}.{name}({', '.join(args)})")
        if self.app == "C3DC" and c3dc_read_statbar:
            for tab in C3DC_VERIFY_TABS:
                self.emit(f'{v}.verify_tab("{tab}")')

    def tab_name(self, args):
        table = _unquote(args[2])
        base = table.split("/")[-1]
        if self.app == "C3DC":
            return re.sub(r"-Tbl$", "", base)
        return re.sub(r"^(GC|CDS)_|Table$", "", base)     # GC_ParticipantsTable -> Participants

    def click(self, path):
        v = self.v
        parts = _obj_parts(path, self.app)
        name = parts[-1]
        if re.search(r"Warning.*Continue|Continue_Btn", name):
            if not self.banner_done:
                self.emit(f"{v}.accept_banner()")
                self.banner_done = True
        elif name == "Explore-Tab":
            self.emit(f"{v}.open_explore()")
        elif name in ("CDS_Data-Btn", "GC_Data-Btn"):
            self.emit(f"{v}.open_data()")
        elif re.search(r"[-_]Chkbx$", name):
            group = "/".join(parts[-3:-1])
            value = re.sub(r"[-_]Chkbx$", "", name)
            try:
                g = self.repo.filter_group(group)
                if not g.knows(value):
                    raise KeyError(f"'{value}' is not a checkbox in {group} in the Katalon Object Repository")
            except Exception as e:
                self.unconverted(f"filter {group} / {value}: {e}")
                return
            self.emit(f'{v}.select_filter("{group}", "{value}")')
        elif re.search(r"[-_](Ddn|Facet)$", name) or name.endswith("Facet") or name.endswith("_Scroll"):
            return              # select_filter opens the facet / dropdown itself
        elif re.search(r"(Tab|Colm)$", name) and parts[0] in ("ResultTabs", "Data_page"):
            return              # verify_tab opens the tab; sort clicks are not needed (compare ignores order)
        else:
            key = "/".join(parts)
            if self.repo.has(key):
                self.emit(f'{v}.click("{key}")')
            else:
                self.unconverted(f"click {path}")


# --------------------------------------------------------------------------- suites
def load_suite_markers(katalon: Path, app: str):
    """{'Test Cases/C3DC_TestCases/.../TC01': {'smoke', 'regression'}}"""
    katalon_app = KATALON_APP.get(app, app)
    out = defaultdict(set)
    for ts in (katalon / "Test Suites").glob("*.ts"):
        marker = SUITE_MARKERS.get(ts.stem)
        if not marker or not ts.stem.upper().startswith(katalon_app):
            continue
        root = ET.parse(ts).getroot()
        for link in root.findall("testCaseLink"):
            if link.findtext("isRun") == "true":
                out[link.findtext("testCaseId")].add(marker)
    return out


# --------------------------------------------------------------------------- writing
def slug_dir(part: str) -> str:
    if re.fullmatch(r"phs\d+.*", part):
        return part
    return re.sub(r"[^A-Za-z0-9]+", "_", part).strip("_").lower()


def py_name(tc_name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", tc_name).strip("_")


def render(app, tc_name, tc_id, markers, steps, todo, input_file):
    v = FIXTURE[app]
    fn = "test_" + py_name(tc_name)
    lines = [HEADER, f'"""{tc_name}\n\nKatalon: {tc_id}\nInput:   InputFiles/{app}/{input_file or "?"}\n"""\n',
             "import pytest\n\n"]
    lines.append(f"@pytest.mark.{app.lower()}")
    for m in sorted(markers):
        lines.append(f"@pytest.mark.{m}")
    if todo:
        reason = "contains Katalon steps that were not converted: " + "; ".join(todo)
        lines.append(f"@pytest.mark.skip(reason={reason[:200]!r})")
    lines.append(f"def {fn}({v}):")
    lines += steps or ["    pass"]
    lines.append(f"    {v}.assert_no_failures()")
    return "\n".join(lines) + "\n"


def generate(katalon: Path, app: str, out_root: Path, force: bool):
    repo = ObjectRepository(app)
    katalon_app = KATALON_APP.get(app, app)
    scripts_root = katalon / "Scripts" / f"{katalon_app}_TestCases"
    suite_markers = load_suite_markers(katalon, app)
    stats = defaultdict(list)
    written_names = {}

    for script in sorted(scripts_root.rglob("Script*.groovy")):
        tc_dir = script.parent
        rel = tc_dir.relative_to(katalon / "Scripts")             # C3DC_TestCases/Studies/phs000466/TC01...
        tc_id = "Test Cases/" + rel.as_posix()
        tc_name = tc_dir.name
        src = strip_comments(script.read_text(errors="ignore"))
        if any(m in src for m in HAND_WRITTEN_MARKERS):
            stats["hand-written (static pages)"].append(tc_name)
            continue
        if any(m in src for m in OUT_OF_SCOPE_MARKERS):
            stats["not converted (standalone Python quick-run script)"].append(tc_name)
            continue
        calls = parse_calls(src)
        tr = Translator(app, repo)
        tr.translate(calls)
        input_file = next((_unquote(a[0]) for k, n, a, o in calls if n == "RunKatalon"), "")
        if input_file:
            input_file = input_file.replace("_CDS_", "_GC_")
        if not any(n == "multiFunction" for k, n, a, o in calls):
            stats["skipped (no data verification steps)"].append(tc_name)
            continue

        sub = [slug_dir(p) for p in rel.parts[1:-1]]
        out_dir = out_root / app.lower() / Path(*sub)
        out_file = out_dir / f"test_{py_name(tc_name)}.py"
        if out_file in written_names:
            stats["duplicate name (not written)"].append(f"{tc_id} clashes with {written_names[out_file]}")
            continue
        written_names[out_file] = tc_id

        text = render(app, tc_name, tc_id, suite_markers.get(tc_id, set()),
                      tr.steps, tr.todo, input_file)
        if out_file.exists() and not force and not out_file.read_text().startswith(HEADER):
            stats["kept (hand edited)"].append(tc_name)
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        for d in [out_dir, *out_dir.relative_to(out_root).parents]:
            init = (out_root / d / "__init__.py") if d != Path(".") else None
            if init and not init.exists():
                init.write_text("")
        out_file.write_text(text)
        stats["with unconverted steps (marked skip)" if tr.todo else "generated"].append(tc_name)
    return stats


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--katalon", required=True)
    ap.add_argument("--apps", nargs="+", default=["C3DC", "GC"])
    ap.add_argument("--out", default=str(ROOT / "Testcases"))
    ap.add_argument("--force", action="store_true", help="overwrite even hand-edited files")
    args = ap.parse_args()
    for app in args.apps:
        stats = generate(Path(args.katalon), app, Path(args.out), args.force)
        print(f"\n== {app}")
        for k, v in stats.items():
            print(f"  {k}: {len(v)}")
            if k != "generated":
                for n in v[:6]:
                    print(f"      - {n}")
                if len(v) > 6:
                    print(f"      ... and {len(v) - 6} more")


if __name__ == "__main__":
    main()
